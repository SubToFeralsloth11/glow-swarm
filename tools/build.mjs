// Bundles src/*.js (ES modules) into one classic script, glowswarm.js.
//
// Why: browsers refuse to load <script type="module"> from file:// URLs, so
// double-clicking index.html would show the menu but nothing would run.
// A classic script works from file://, a local server and GitHub Pages alike.
//
// Each module becomes a function scope inside one IIFE. Its `import { a } from './x.js'`
// lines become `const { a } = modules.x`, and its `export` keywords are stripped and
// collected into the returned object. Only those two simple forms are supported;
// anything else fails the build loudly.
//
// Usage: node tools/build.mjs          writes glowswarm.js
//        node tools/build.mjs --check  exits 1 if glowswarm.js is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'glowswarm.js');
const IMPORT = /^import \{([^}]+)\} from '\.\/(\w+)\.js';$/;
const EXPORT = /^export (const|let|function|class) (\w+)/;

function load(name) {
  const lines = readFileSync(join(root, 'src', `${name}.js`), 'utf8').split('\n');
  const deps = [];
  const exports = [];
  const body = lines.map((line, i) => {
    if (line.startsWith('import ')) {
      const m = line.match(IMPORT);
      if (!m) throw new Error(`src/${name}.js:${i + 1}: unsupported import: ${line}`);
      deps.push(m[2]);
      return `const {${m[1]}} = modules.${m[2]};`;
    }
    if (line.startsWith('export ')) {
      const m = line.match(EXPORT);
      if (!m) throw new Error(`src/${name}.js:${i + 1}: unsupported export: ${line}`);
      exports.push(m[2]);
      return line.slice('export '.length);
    }
    return line;
  });
  return { name, deps, exports, body };
}

// Dependency-first order, starting from the entry point.
function order(entry) {
  const seen = new Map();
  const out = [];
  const visit = (name, stack) => {
    if (stack.includes(name)) throw new Error(`import cycle: ${[...stack, name].join(' -> ')}`);
    if (seen.has(name)) return;
    const mod = load(name);
    seen.set(name, mod);
    for (const d of mod.deps) visit(d, [...stack, name]);
    out.push(mod);
  };
  visit(entry, []);
  return out;
}

export function bundle() {
  const parts = ['// GENERATED by tools/build.mjs from src/*.js. Do not edit; run `npm run build`.', '(() => {', "'use strict';", 'const modules = {};'];
  for (const mod of order('main')) {
    parts.push(`// ---- src/${mod.name}.js ----`, `modules.${mod.name} = (() => {`, ...mod.body, `return { ${mod.exports.join(', ')} };`, '})();');
  }
  parts.push('})();', '');
  return parts.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}` || fileURLToPath(import.meta.url) === process.argv[1]) {
  const code = bundle();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== code) {
      console.error('glowswarm.js is out of date: run `npm run build`.');
      process.exit(1);
    }
    console.log('glowswarm.js is up to date.');
  } else {
    writeFileSync(OUT, code);
    console.log(`wrote glowswarm.js (${(code.length / 1024).toFixed(1)} KB)`);
  }
}
